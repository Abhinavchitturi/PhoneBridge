import AppKit
import CryptoKit

/// Mac clipboard → phone automatically; phone → Mac when the phone sends it. Text and images.
final class ClipboardSync {
    var send: (String) -> Void = { _ in }
    var sendImage: (Data) -> Void = { _ in }
    /// (text, came from the phone) — feeds the clipboard history.
    var onText: (String, Bool) -> Void = { _, _ in }
    private var lastImageHash: Data?
    private var lastChange = NSPasteboard.general.changeCount
    // Last text seen in either direction. scrcpy's clipboard sync and our link can both write the
    // same text back and forth; skipping repeats stops that from ping-ponging.
    private var lastText: String?
    private var timer: Timer?
    // Password managers mark secrets with these types; never send those to the phone.
    private let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                          "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if let types = pb.types, types.contains(where: { skipTypes.contains($0.rawValue) }) { return }
        if let s = pb.string(forType: .string) {
            guard !s.isEmpty, s.utf8.count < 1_000_000, s != lastText else { return }
            lastText = s
            onText(s, false)
            send(s)
        } else if let png = Self.pngFromPasteboard(pb), png.count < 8_000_000 {
            let hash = Data(SHA256.hash(data: png))
            guard hash != lastImageHash else { return }
            lastImageHash = hash
            sendImage(png)
        }
    }

    private static func pngFromPasteboard(_ pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    func setImageFromPhone(_ png: Data) {
        lastImageHash = Data(SHA256.hash(data: png))
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setData(png, forType: .png)
        if let tiff = NSImage(data: png)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
        lastChange = pb.changeCount
    }

    func setFromPhone(_ text: String) {
        lastText = text
        onText(text, true)
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChange = pb.changeCount // don't echo it back
    }
}

/// File transfers in both directions; incoming files land in ~/Downloads.
final class Transfers {
    private static let chunk = 192 * 1024
    private final class Incoming {
        let handle: FileHandle
        let url: URL
        let kind: String?
        let total: Int64
        var got: Int64 = 0
        var lastReport = Date.distantPast
        init(handle: FileHandle, url: URL, kind: String?, total: Int64) {
            self.handle = handle; self.url = url; self.kind = kind; self.total = total
        }
    }
    private var incoming: [String: Incoming] = [:]
    /// (file, kind) — kind is e.g. "photo:123" for a Photos-tab download, nil for a normal file.
    var onReceived: (URL, String?) -> Void = { _, _ in }
    /// (kind, bytes so far, total bytes) while a file arrives; throttled to a few times a second.
    var onProgress: (String?, Int64, Int64) -> Void = { _, _, _ in }

    func handle(_ m: [String: Any]) {
        guard let fid = m["fid"] as? String else { return }
        switch m["t"] as? String {
        case "file_start":
            let name = (m["name"] as? String ?? "file").replacingOccurrences(of: "/", with: "_")
            let kind = m["kind"] as? String
            // Photos opened in the viewer go to a cache; "Download" copies them to Downloads.
            let dir = kind?.hasPrefix("photo:") == true ? Self.photoCache
                : FileManager.default.urls(for: .downloadsDirectory, in: .userDomainMask)[0]
            let url = Self.uniqueURL(in: dir, name: name)
            FileManager.default.createFile(atPath: url.path, contents: nil)
            if let h = try? FileHandle(forWritingTo: url) {
                incoming[fid] = Incoming(handle: h, url: url, kind: kind, total: (m["size"] as? NSNumber)?.int64Value ?? -1)
                onProgress(kind, 0, (m["size"] as? NSNumber)?.int64Value ?? -1)
            }
        case "file_chunk":
            if let f = incoming[fid], let b64 = m["data"] as? String, let d = Data(base64Encoded: b64) {
                f.handle.write(d)
                f.got += Int64(d.count)
                if Date().timeIntervalSince(f.lastReport) > 0.15 {
                    f.lastReport = Date()
                    onProgress(f.kind, f.got, f.total)
                }
            }
        case "file_end":
            if let f = incoming.removeValue(forKey: fid) {
                try? f.handle.close()
                onReceived(f.url, f.kind)
            }
        default:
            break
        }
    }

    /// Streams a file to the phone, waiting for each chunk so memory stays flat.
    func send(_ url: URL, via link: PhoneLink, kind: String? = nil, done: @escaping (Bool) -> Void) {
        Thread.detachNewThread {
            func sendWait(_ m: [String: Any]) -> Bool {
                let sem = DispatchSemaphore(value: 0)
                var ok = false
                link.send(m) { ok = $0; sem.signal() }
                sem.wait()
                return ok
            }
            guard let h = try? FileHandle(forReadingFrom: url) else { return done(false) }
            defer { try? h.close() }
            let fid = UUID().uuidString
            let size = (try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? -1
            var start: [String: Any] = ["t": "file_start", "fid": fid, "name": url.lastPathComponent, "size": size,
                                        "mime": Self.mime(url)]
            if let kind { start["kind"] = kind }
            guard sendWait(start) else { return done(false) }
            while let d = try? h.read(upToCount: Self.chunk), !d.isEmpty {
                guard sendWait(["t": "file_chunk", "fid": fid, "data": d.base64EncodedString()]) else { return done(false) }
            }
            done(sendWait(["t": "file_end", "fid": fid]))
        }
    }

    private static func mime(_ url: URL) -> String {
        (try? url.resourceValues(forKeys: [.contentTypeKey]).contentType?.preferredMIMEType) ?? "application/octet-stream"
    }

    static let photoCache: URL = {
        let dir = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("PhoneBridge/Photos", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()

    /// Full-size photos only live here while you look at them.
    static func wipePhotoCache() {
        let fm = FileManager.default
        for url in (try? fm.contentsOfDirectory(at: photoCache, includingPropertiesForKeys: nil)) ?? [] {
            try? fm.removeItem(at: url)
        }
        try? fm.removeItem(at: fm.temporaryDirectory.appendingPathComponent("PhoneBridgeIcons"))
    }

    static func uniqueURL(in dir: URL, name: String) -> URL {
        var url = dir.appendingPathComponent(name)
        let base = (name as NSString).deletingPathExtension
        let ext = (name as NSString).pathExtension
        var i = 2
        while FileManager.default.fileExists(atPath: url.path) {
            url = dir.appendingPathComponent(ext.isEmpty ? "\(base) \(i)" : "\(base) \(i).\(ext)")
            i += 1
        }
        return url
    }
}
